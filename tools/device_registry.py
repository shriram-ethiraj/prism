"""Validate public device findings and generate the compatibility table. No network."""
import argparse
import json
import posixpath
from pathlib import Path
from prism_runtime import ROOT

RESULTS = ("installation", "apps", "inputs", "fullscreen", "home", "standby", "cold_boot", "recovery")
STATUSES = {"verified", "pending", "failed", "reported"}


def profiles():
    records = []
    identities = set()
    for path in sorted((ROOT / "devices").glob("*.json")):
        record = json.loads(path.read_text())
        for field in ("id", "model", "firmware", "tizen", "web_engine", "architecture", "runtime", "privilege", "test_date", "evidence", "results", "notes", "logical_surface", "native", "accepted_reports"):
            if field not in record:
                raise ValueError(f"{path.name}: missing {field}")
        if record.get("schema") != 1 or record["id"] != path.stem:
            raise ValueError(f"{path.name}: invalid identity/schema")
        key = (record["model"], record["firmware"])
        if key in identities:
            raise ValueError("Duplicate exact device configuration")
        identities.add(key)
        if set(record["results"]) != set(RESULTS) or not set(record["results"].values()) <= STATUSES:
            raise ValueError(f"{path.name}: invalid evidence statuses")
        surface = record["logical_surface"]
        if (surface["width"], surface["height"]) not in {(1280, 720), (1920, 1080), (3840, 2160)}:
            raise ValueError("Surface requires a reviewed 16:9 logical configuration")
        for field in ("evidence", "notes"):
            target = (path.parent / record[field]).resolve()
            if not target.is_relative_to(ROOT) or not target.is_file():
                raise ValueError(f"{path.name}: missing local {field}")
        for report in record["accepted_reports"]:
            if not report.startswith("https://github.com/shriram-ethiraj/prism/issues/"):
                raise ValueError("Accepted report must link to a reviewed Prism issue")
        records.append(record)
    return records


def render(records):
    tested = sum("verified" in r["results"].values() for r in records)
    reports = len({u for r in records for u in r["accepted_reports"]})
    lines = ["# Verified devices", "", "Prism targets Samsung Tizen monitors. These are exact configurations with recorded evidence, not a promise for every model running the same Tizen version.", "", f"**{tested} Prism-tested configuration(s); {reports} accepted community report(s).** Reports do not establish a count of unique physical devices or installations.", "", "Generated by `python3 tools/device_registry.py`; edit the reviewed JSON profiles under `devices/`, then regenerate.", "", "| Model / firmware | Prism build | Install | Apps | Inputs | Fullscreen | Home | Standby | Cold boot | Recovery |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in records:
        name = f"[{r['model']} / {r['firmware']}](devices/{r['id']}.json)"
        lines.append("| " + " | ".join([name, r.get("prism_build") or "—", *(r["results"][k] for k in RESULTS)]) + " |")
    lines.extend(["", "**verified** = exact-device Prism evidence, with physical observation where required. **reported** = owner report awaiting full confirmation. **pending** = not established. **failed** = observed failure.", "", "## Reusable technical findings", "", "Profiles link to notes with native Home/startup constants, API/library symbols, application IDs, foreground key codes, logical display dimensions, runtime/privilege requirements, and applicability. Read those notes before reuse. Public findings never replace the target device's private original-settings baseline.", ""])
    for r in records:
        notes = posixpath.normpath("devices/" + r["notes"])
        lines.append(f"- [{r['id']}]({notes}): {r['evidence_note']} Evidence date: {r['test_date']}; {r['privilege']}, {r['tizen']}, {r['web_engine']}, {r['architecture']}, {r['runtime']}.")
    lines.extend(["", "## Test another monitor", "", "Follow [setup and adaptation](docs/setup.md). Physical Home from streaming apps and native input, standby resume, cold boot, fullscreen fit, and restoration are independent checks. Successful installation does not imply the others passed. Firmware changes require a new configuration and revalidation.", "", "[Submit a device report](https://github.com/shriram-ethiraj/prism/issues/new?template=device-report.yml), including partial success and failures. Maintainers review reports before adding verified results. Remove private information from screenshots and never attach credentials, raw device logs, addresses, or recovery records.", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(profiles())
    target = ROOT / "VERIFIED_DEVICES.md"
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit("Device registry is stale; run python3 tools/device_registry.py")
        print("Device profiles and registry match.")
    else:
        target.write_text(content)
